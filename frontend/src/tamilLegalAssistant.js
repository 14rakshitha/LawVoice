export function buildTamilLegalAnswer(query = '') {
  const text = query.toLowerCase();
  const matched = rules.find(([, keywords]) => keywords.some((keyword) => text.includes(keyword.toLowerCase())));
  const key = matched ? matched[0] : 'general';
  const answer = tamilAnswers[key];
  return {
    ...answer,
    suggestedLawyers: getSuggestedLawyers(answer.category),
    sources: [],
    disclaimer: 'இது பொதுவான சட்ட விழிப்புணர்வு வழிகாட்டல் மட்டுமே. உங்கள் வழக்கின் ஆவணங்கள் மற்றும் உள்ளூர் நடைமுறைக்கு ஏற்ப வழக்கறிஞரிடம் தனிப்பட்ட ஆலோசனை பெறுங்கள்.'
  };
}

function getSuggestedLawyers(category) {
  const savedLawyer = readStoredLawyerProfile();
  const saved = {
    id: 'saved-lawyer',
    name: savedLawyer.name,
    category: savedLawyer.category,
    city: savedLawyer.city,
    phone: savedLawyer.phone,
    rating: '4.9'
  };
  return [saved, ...demoLawyers]
    .filter((lawyer, index, all) => all.findIndex((item) => item.name === lawyer.name) === index)
    .filter((lawyer) => lawyer.category === category)
    .slice(0, 3);
}
